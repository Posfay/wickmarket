// A függvényként megadott bejegyzések (params, helpers) párost kapnak; lásd src/core/i18n.js.
//
// Nyelvtani fogás: a változó szavak (piac-, klán- és árunevek) ragozás nélkül kerülnek a mondatba
// (kettősponttal vagy zárójelben), kivéve a piacneveket: ezek mindig „piac”-ra végződnek, így az
// -on / -ra / -ról rag mindig helyes ("a Dombi piacon"). A tárgyragos árunevek külön kulcsok (.acc).

const piacon = (h, m) => { const n = h.market(m); return `${h.az(n)} ${n}on`; };
const piacra = (h, m) => { const n = h.market(m); return `${h.az(n)} ${n}ra`; };
const piacrol = (h, m) => { const n = h.market(m); return `${h.az(n)} ${n}ról`; };
/** "3 bogyót", "1 kenyeret" (tárgyeset). */
const db = (h, n, g) => `${h.int(n)} ${h.t(`good.${g}.acc`)}`;
/** "A Méz és a Dér klán" (mondat elején). */
const ket = (h, a, b) => { const x = h.clan(a), y = h.clan(b); return `${h.cap(h.az(x))} ${x} és ${h.az(y)} ${y} klán`; };
/** "a Méz és a Dér klán között". */
const kozott = (h, a, b) => { const x = h.clan(a), y = h.clan(b); return `${h.az(x)} ${x} és ${h.az(y)} ${y} klán között`; };

